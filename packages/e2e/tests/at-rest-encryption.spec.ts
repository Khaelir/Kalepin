import { test, expect } from '../fixtures';
import jwt from 'jsonwebtoken';
import fs from 'fs';
import path from 'path';
import {
  BACKEND_PORT,
  PERSONAL_PATH,
  VAULT_PATH,
  KEK_PATH,
} from '../playwright.config';

const API = `http://localhost:${BACKEND_PORT}`;
const ENVELOPE_MAGIC = Buffer.from([0x4b, 0x45, 0x31, 0x00]); // "KE1\0"

let subCounter = 8000;

function makeToken(email: string): string {
  return jwt.sign({ sub: ++subCounter, email }, 'test-secret', { expiresIn: '1h' });
}

function hasMagic(buf: Buffer): boolean {
  return (
    buf.length >= 4 &&
    buf[0] === ENVELOPE_MAGIC[0] &&
    buf[1] === ENVELOPE_MAGIC[1] &&
    buf[2] === ENVELOPE_MAGIC[2] &&
    buf[3] === ENVELOPE_MAGIC[3]
  );
}

async function createNoteViaAPI(token: string, virtualPath: string, body: string): Promise<void> {
  const res = await fetch(`${API}/api/files/create`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${token}`,
    },
    body: JSON.stringify({ path: virtualPath, content: body }),
  });
  if (!res.ok) throw new Error(`create failed: ${res.status} ${await res.text()}`);
}

async function readNoteViaAPI(token: string, virtualPath: string): Promise<string> {
  const res = await fetch(
    `${API}/api/files/read?path=${encodeURIComponent(virtualPath)}`,
    { headers: { Authorization: `Bearer ${token}` } },
  );
  if (!res.ok) throw new Error(`read failed: ${res.status}`);
  const json = await res.json();
  return json.content;
}

test.describe('At-rest encryption — defaults (personal=ON, shared=OFF)', () => {
  test('writes to _users/* land as envelopes on disk; vault/* stays plaintext', async () => {
    // Sanity: KEK file was auto-generated by the harness.
    expect(fs.existsSync(KEK_PATH)).toBe(true);
    const kekStat = fs.statSync(KEK_PATH);
    expect(kekStat.size).toBe(32);

    const alice = `alice-enc-${Date.now()}@example.com`;
    const aliceToken = makeToken(alice);

    const personalRel = `Diary-${Date.now()}.md`;
    const personalVirtual = `_users/${alice}/${personalRel}`;
    const personalBody = '# Diary\n\nA secret thought.\n';
    await createNoteViaAPI(aliceToken, personalVirtual, personalBody);

    const sharedRel = `Notes/Public-${Date.now()}.md`;
    const sharedBody = '# Public\n\nVisible to all.\n';
    await createNoteViaAPI(aliceToken, sharedRel, sharedBody);

    // Disk inspection — personal must be an envelope; shared must be plaintext.
    const personalDisk = path.join(PERSONAL_PATH, alice, personalRel);
    const sharedDisk = path.join(VAULT_PATH, sharedRel);

    expect(fs.existsSync(personalDisk)).toBe(true);
    expect(fs.existsSync(sharedDisk)).toBe(true);

    const personalBytes = fs.readFileSync(personalDisk);
    const sharedBytes = fs.readFileSync(sharedDisk);

    expect(
      hasMagic(personalBytes),
      `expected envelope magic at ${personalDisk}, got prefix ${personalBytes.subarray(0, 8).toString('hex')}`,
    ).toBe(true);
    expect(
      hasMagic(sharedBytes),
      `expected plaintext at ${sharedDisk}, got envelope`,
    ).toBe(false);

    // Plaintext bytes never touch the personal envelope.
    expect(personalBytes.includes(Buffer.from('A secret thought.'))).toBe(false);

    // API still serves plaintext for both.
    const personalRead = await readNoteViaAPI(aliceToken, personalVirtual);
    const sharedRead = await readNoteViaAPI(aliceToken, sharedRel);
    expect(personalRead).toContain('A secret thought.');
    expect(sharedRead).toContain('Visible to all.');
  });

  test('admin GET /api/admin/encryption reports per-zone state with personal=ON, shared=OFF', async () => {
    const adminToken = makeToken('admin@kalepin.local');
    const res = await fetch(`${API}/api/admin/encryption`, {
      headers: { Authorization: `Bearer ${adminToken}` },
    });
    expect(res.ok).toBe(true);
    const data = await res.json();
    expect(Array.isArray(data.zones)).toBe(true);

    const zoneByName = Object.fromEntries(
      data.zones.map((z: { zone: string }) => [z.zone, z]),
    );
    expect(zoneByName.personal.enabled).toBe(true);
    expect(zoneByName.shared.enabled).toBe(false);
    expect(zoneByName.personal.kek_fingerprint).toMatch(/^[0-9a-f]{16}$/);
  });
});
